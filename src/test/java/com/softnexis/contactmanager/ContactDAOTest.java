package com.softnexis.contactmanager;

import com.softnexis.contactmanager.dao.ContactDAO;
import com.softnexis.contactmanager.dao.ContactDAOImpl;
import com.softnexis.contactmanager.model.Contact;
import com.softnexis.contactmanager.util.ContactCsvMigrator;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.io.StringReader;
import java.io.StringWriter;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Arrays;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

@DisplayName("Task 3: ContactDAO Database Integration Tests (JDBC + SQL)")
public class ContactDAOTest {

    private JdbcDataSource dataSource;
    private ContactDAO contactDAO;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:testdb;MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        dataSource.setPassword("");

        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS contacts");
            stmt.execute("CREATE TABLE contacts (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "name VARCHAR(100) NOT NULL, " +
                    "email VARCHAR(100) NOT NULL UNIQUE, " +
                    "phone VARCHAR(20), " +
                    "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP" +
                    ")");
            stmt.execute("CREATE INDEX idx_contacts_name ON contacts(name)");
            stmt.execute("CREATE INDEX idx_contacts_email ON contacts(email)");
        }

        contactDAO = new ContactDAOImpl(dataSource);
    }

    @AfterEach
    void tearDown() throws Exception {
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS contacts");
        }
    }

    @Test
    @DisplayName("addContact persists contact and populates generated ID")
    void testAddContact() throws SQLException {
        Contact contact = new Contact(null, "Alice Johnson", "alice@example.com", "5551234567");
        contactDAO.addContact(contact);

        assertNotNull(contact.getId(), "Generated ID must be assigned");
        assertTrue(contact.getId() > 0);

        Optional<Contact> fetched = contactDAO.getContactById(contact.getId());
        assertTrue(fetched.isPresent());
        assertEquals("Alice Johnson", fetched.get().getName());
        assertEquals("alice@example.com", fetched.get().getEmail());
        assertEquals("5551234567", fetched.get().getPhone());
    }

    @Test
    @DisplayName("Duplicate email throws SQLException (Unique constraint)")
    void testDuplicateEmailConstraintViolation() throws SQLException {
        Contact c1 = new Contact(null, "User One", "dup@example.com", "5551112222");
        contactDAO.addContact(c1);

        Contact c2 = new Contact(null, "User Two", "dup@example.com", "5553334444");
        SQLException ex = assertThrows(SQLException.class, () -> contactDAO.addContact(c2));

        // Verify SQLState or message indicates constraint violation
        assertTrue(ex.getSQLState() != null || ex.getMessage() != null);
    }

    @Test
    @DisplayName("searchContacts matches case-insensitive name, email, or phone")
    void testSearchContacts() throws SQLException {
        contactDAO.addContact(new Contact(null, "Johnathan Doe", "jdoe@company.org", "5551002000"));
        contactDAO.addContact(new Contact(null, "Jane Smith", "jane.smith@corporate.net", "5553004000"));
        contactDAO.addContact(new Contact(null, "Bob Builder", "bob@builder.com", "5559998888"));

        // Match name
        List<Contact> byName = contactDAO.searchContacts("john");
        assertEquals(1, byName.size());
        assertEquals("Johnathan Doe", byName.get(0).getName());

        // Match email
        List<Contact> byEmail = contactDAO.searchContacts("corporate");
        assertEquals(1, byEmail.size());
        assertEquals("Jane Smith", byEmail.get(0).getName());

        // Match phone
        List<Contact> byPhone = contactDAO.searchContacts("9998888");
        assertEquals(1, byPhone.size());
        assertEquals("Bob Builder", byPhone.get(0).getName());

        // Empty search returns all contacts
        List<Contact> all = contactDAO.searchContacts("");
        assertEquals(3, all.size());
    }

    @Test
    @DisplayName("updateContact updates fields correctly")
    void testUpdateContact() throws SQLException {
        Contact contact = new Contact(null, "Original Name", "original@test.com", "5550000000");
        contactDAO.addContact(contact);

        contact.setName("Updated Name");
        contact.setEmail("updated@test.com");
        contact.setPhone("5559999999");
        boolean updated = contactDAO.updateContact(contact);
        assertTrue(updated);

        Optional<Contact> refetched = contactDAO.getContactById(contact.getId());
        assertTrue(refetched.isPresent());
        assertEquals("Updated Name", refetched.get().getName());
        assertEquals("updated@test.com", refetched.get().getEmail());
        assertEquals("5559999999", refetched.get().getPhone());
    }

    @Test
    @DisplayName("deleteContact removes record by ID")
    void testDeleteContact() throws SQLException {
        Contact contact = new Contact(null, "To Delete", "delete.me@test.com", "5551239999");
        contactDAO.addContact(contact);

        boolean deleted = contactDAO.deleteContact(contact.getId());
        assertTrue(deleted);

        Optional<Contact> notFound = contactDAO.getContactById(contact.getId());
        assertFalse(notFound.isPresent());
    }

    @Test
    @DisplayName("isEmailDuplicate detects existing email excluding specific ID")
    void testIsEmailDuplicate() throws SQLException {
        Contact contact = new Contact(null, "Test Exclude", "check@test.com", "5550001111");
        contactDAO.addContact(contact);

        assertTrue(contactDAO.isEmailDuplicate("check@test.com", null));
        assertTrue(contactDAO.isEmailDuplicate("CHECK@TEST.COM", null));
        // Excluding its own ID should return false (allows updating own record)
        assertFalse(contactDAO.isEmailDuplicate("check@test.com", contact.getId()));
        assertFalse(contactDAO.isEmailDuplicate("random@test.com", null));
    }

    @Test
    @DisplayName("addContactsBatch bulk inserts using JDBC batch processing")
    void testBatchInsert() throws SQLException {
        List<Contact> list = Arrays.asList(
                new Contact(null, "Batch One", "batch1@test.com", "5550000001"),
                new Contact(null, "Batch Two", "batch2@test.com", "5550000002"),
                new Contact(null, "Batch Three", "batch3@test.com", "5550000003")
        );

        contactDAO.addContactsBatch(list);

        assertEquals(3, contactDAO.countContacts());
        List<Contact> all = contactDAO.getAllContacts();
        assertEquals(3, all.size());
    }

    @Test
    @DisplayName("ContactCsvMigrator exports to CSV and imports back into database")
    void testCsvMigration() throws Exception {
        contactDAO.addContact(new Contact(null, "Export User", "export@test.com", "5554445555"));

        StringWriter writer = new StringWriter();
        List<Contact> contacts = contactDAO.getAllContacts();
        ContactCsvMigrator.exportContactsToCsv(contacts, writer);

        String csvOutput = writer.toString();
        assertTrue(csvOutput.contains("Export User"));
        assertTrue(csvOutput.contains("export@test.com"));

        // Test Import CSV
        String csvToImport = "id,name,email,phone,created_at\n" +
                ",Imported User,imported@test.com,5557778888,2026-10-05T12:00:00\n";
        StringReader reader = new StringReader(csvToImport);
        int importedCount = ContactCsvMigrator.importContactsFromCsv(reader, contactDAO);

        assertEquals(1, importedCount);
        assertTrue(contactDAO.isEmailDuplicate("imported@test.com", null));
    }
}
