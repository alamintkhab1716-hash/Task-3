package com.softnexis.contactmanager;

import com.softnexis.contactmanager.controller.AddContactServlet;
import com.softnexis.contactmanager.controller.ContactServlet;
import com.softnexis.contactmanager.dao.ContactDAO;
import com.softnexis.contactmanager.dao.ContactDAOImpl;
import com.softnexis.contactmanager.model.Contact;
import com.softnexis.contactmanager.service.ContactService;
import com.softnexis.contactmanager.service.JdbcContactService;
import com.softnexis.contactmanager.util.CsrfTokenManager;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import javax.servlet.RequestDispatcher;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;
import javax.servlet.http.HttpSession;
import java.sql.Connection;
import java.sql.Statement;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyBoolean;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.*;

@DisplayName("Task 3: Servlet Controller Tests with ContactDAO")
public class ContactServletTest {

    private JdbcDataSource dataSource;
    private ContactDAO contactDAO;
    private ContactService contactService;

    private ContactServlet contactServlet;
    private AddContactServlet addContactServlet;

    private HttpServletRequest request;
    private HttpServletResponse response;
    private HttpSession session;
    private RequestDispatcher requestDispatcher;

    private Map<String, Object> sessionAttributes;
    private Map<String, Object> requestAttributes;

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:servlet_testdb;MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        dataSource.setPassword("");

        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS contacts");
            stmt.execute("CREATE TABLE contacts (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "name VARCHAR(100) NOT NULL, " +
                    "email VARCHAR(100) NOT NULL UNIQUE, " +
                    "phone VARCHAR(20), " +
                    "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP" +
                    ")");
            stmt.execute("CREATE INDEX idx_contacts_name ON contacts(name)");
            stmt.execute("CREATE INDEX idx_contacts_email ON contacts(email)");
        }

        contactDAO = new ContactDAOImpl(dataSource);
        contactService = new JdbcContactService(contactDAO);

        contactServlet = new ContactServlet();
        addContactServlet = new AddContactServlet();

        contactServlet.setContactDAO(contactDAO);
        contactServlet.setContactService(contactService);
        addContactServlet.setContactDAO(contactDAO);
        addContactServlet.setContactService(contactService);
        contactServlet.setAddContactServlet(addContactServlet);

        request = mock(HttpServletRequest.class);
        response = mock(HttpServletResponse.class);
        session = mock(HttpSession.class);
        requestDispatcher = mock(RequestDispatcher.class);

        sessionAttributes = new HashMap<>();
        requestAttributes = new HashMap<>();

        when(request.getSession(anyBoolean())).thenReturn(session);
        when(request.getSession()).thenReturn(session);
        when(request.getContextPath()).thenReturn("/test");
        when(request.getRequestDispatcher(anyString())).thenReturn(requestDispatcher);

        doAnswer(invocation -> {
            String key = invocation.getArgument(0);
            return sessionAttributes.get(key);
        }).when(session).getAttribute(anyString());

        doAnswer(invocation -> {
            String key = invocation.getArgument(0);
            Object val = invocation.getArgument(1);
            sessionAttributes.put(key, val);
            return null;
        }).when(session).setAttribute(anyString(), any());

        doAnswer(invocation -> {
            String key = invocation.getArgument(0);
            Object val = invocation.getArgument(1);
            requestAttributes.put(key, val);
            return null;
        }).when(request).setAttribute(anyString(), any());
    }

    @AfterEach
    void tearDown() throws Exception {
        try (Connection conn = dataSource.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS contacts");
        }
    }

    @Test
    @DisplayName("GET /contacts displays contact list and forwards to contact-list.jsp")
    void testGetContactsList() throws Exception {
        when(request.getServletPath()).thenReturn("/contacts");
        when(request.getPathInfo()).thenReturn(null);

        contactDAO.addContact(new Contact(null, "Test Contact", "test@domain.com", "5551234567"));

        contactServlet.doGet(request, response);

        verify(request).getRequestDispatcher("/contact-list.jsp");
        verify(requestDispatcher).forward(request, response);
        assertTrue(requestAttributes.containsKey("contacts"));
        assertTrue(requestAttributes.containsKey("currentPage"));
        assertTrue(requestAttributes.containsKey("totalPages"));
    }

    @Test
    @DisplayName("GET /contacts?search=keyword filters results via ContactDAO")
    void testGetContactsSearch() throws Exception {
        contactDAO.addContact(new Contact(null, "Sherlock Holmes", "sherlock@bakerstreet.co.uk", "5552211999"));
        contactDAO.addContact(new Contact(null, "John Watson", "watson@bakerstreet.co.uk", "5552212999"));

        when(request.getServletPath()).thenReturn("/contacts");
        when(request.getPathInfo()).thenReturn(null);
        when(request.getParameter("search")).thenReturn("sherlock");

        contactServlet.doGet(request, response);

        verify(request).getRequestDispatcher("/contact-list.jsp");
        verify(requestDispatcher).forward(request, response);

        @SuppressWarnings("unchecked")
        List<Contact> contacts = (List<Contact>) requestAttributes.get("contacts");
        assertNotNull(contacts);
        assertEquals(1, contacts.size());
        assertEquals("Sherlock Holmes", contacts.get(0).getName());
        assertEquals("sherlock", requestAttributes.get("searchQuery"));
    }

    @Test
    @DisplayName("GET /contacts/add displays contact form and sets CSRF token")
    void testGetContactsAdd() throws Exception {
        when(request.getServletPath()).thenReturn("/contacts");
        when(request.getPathInfo()).thenReturn("/add");

        contactServlet.doGet(request, response);

        verify(request).getRequestDispatcher("/contact-form.jsp");
        verify(requestDispatcher).forward(request, response);
        assertTrue(requestAttributes.containsKey("csrfToken"));
        assertNotNull(requestAttributes.get("csrfToken"));
    }

    @Test
    @DisplayName("POST /contacts with valid data saves contact to database and returns 302 redirect")
    void testPostValidContactSubmission() throws Exception {
        String token = CsrfTokenManager.getToken(session);

        when(request.getParameter("name")).thenReturn("Bruce Wayne");
        when(request.getParameter("email")).thenReturn("bruce@wayne-enterprises.com");
        when(request.getParameter("phone")).thenReturn("5551234567");
        when(request.getParameter(CsrfTokenManager.CSRF_TOKEN_PARAM)).thenReturn(token);

        addContactServlet.doPost(request, response);

        // Verify 302 Redirect to /contacts
        verify(response).sendRedirect("/test/contacts");

        // Verify contact is in persistent database via DAO
        List<Contact> all = contactDAO.getAllContacts();
        boolean found = all.stream().anyMatch(c -> "bruce@wayne-enterprises.com".equals(c.getEmail()));
        assertTrue(found, "Saved contact must exist in database");

        // Verify flash toast was set
        assertTrue(sessionAttributes.containsKey("flashToast"));
    }

    @Test
    @DisplayName("POST /contacts with duplicate email produces 'Email already exists' error")
    void testPostDuplicateEmailSubmission() throws Exception {
        contactDAO.addContact(new Contact(null, "Existing User", "duplicate@company.com", "5551112222"));

        String token = CsrfTokenManager.getToken(session);

        when(request.getParameter("name")).thenReturn("Second User");
        when(request.getParameter("email")).thenReturn("duplicate@company.com");
        when(request.getParameter("phone")).thenReturn("5553334444");
        when(request.getParameter(CsrfTokenManager.CSRF_TOKEN_PARAM)).thenReturn(token);

        addContactServlet.doPost(request, response);

        verify(response).setStatus(HttpServletResponse.SC_BAD_REQUEST);
        verify(request).getRequestDispatcher("/contact-form.jsp");
        verify(requestDispatcher).forward(request, response);

        @SuppressWarnings("unchecked")
        Map<String, String> errors = (Map<String, String>) requestAttributes.get("errors");
        assertNotNull(errors);
        assertEquals("Email already exists", errors.get("email"));
    }

    @Test
    @DisplayName("POST /contacts with empty form -> Field-specific errors and 400 Bad Request")
    void testPostEmptyFormSubmission() throws Exception {
        String token = CsrfTokenManager.getToken(session);

        when(request.getParameter("name")).thenReturn("");
        when(request.getParameter("email")).thenReturn("");
        when(request.getParameter("phone")).thenReturn("");
        when(request.getParameter(CsrfTokenManager.CSRF_TOKEN_PARAM)).thenReturn(token);

        addContactServlet.doPost(request, response);

        // Verify HTTP 400 Bad Request
        verify(response).setStatus(HttpServletResponse.SC_BAD_REQUEST);
        verify(request).getRequestDispatcher("/contact-form.jsp");
        verify(requestDispatcher).forward(request, response);

        @SuppressWarnings("unchecked")
        Map<String, String> errors = (Map<String, String>) requestAttributes.get("errors");
        assertNotNull(errors);
        assertEquals("Please enter valid name", errors.get("name"));
        assertEquals("Invalid email address", errors.get("email"));
    }

    @Test
    @DisplayName("GET /contacts/delete deletes contact from database")
    void testDeleteContact() throws Exception {
        Contact contact = new Contact(null, "Delete Target", "target@domain.com", "5558887777");
        contactDAO.addContact(contact);

        when(request.getPathInfo()).thenReturn("/delete");
        when(request.getParameter("id")).thenReturn(String.valueOf(contact.getId()));

        contactServlet.doGet(request, response);

        verify(response).sendRedirect("/test/contacts");
        assertFalse(contactDAO.getContactById(contact.getId()).isPresent());
        assertTrue(sessionAttributes.containsKey("flashToast"));
    }
}
